#!/usr/bin/env python3
"""核对 node_modules 里每个文件和 npm 缓存里的原始 tgz 是否一致，不一致就从 tgz 重写。

背景：这台机器上 npm install 解包偶尔会把文件写成空的或截断的（11-09 发现，原因未查清）。
用法：在 frontend 目录运行 python3 ../scripts/repair_node_modules.py
"""
import base64
import json
import sys
import tarfile
from pathlib import Path

CACHE = Path.home() / ".npm" / "_cacache" / "content-v2"


def cache_path(integrity: str) -> Path | None:
    algo, b64 = integrity.split()[0].split("-", 1)
    hexd = base64.b64decode(b64).hex()
    p = CACHE / algo / hexd[:2] / hexd[2:4] / hexd[4:]
    return p if p.exists() else None


def main() -> int:
    lock = json.loads(Path("package-lock.json").read_text())
    fixed = checked = missing = 0
    for key, meta in lock.get("packages", {}).items():
        if not key or "integrity" not in meta or not key.startswith("node_modules/"):
            continue
        dest = Path(key)
        if not dest.exists():
            continue  # 平台不匹配的可选依赖
        tgz = cache_path(meta["integrity"])
        if tgz is None:
            missing += 1
            continue
        with tarfile.open(tgz, "r:gz") as tar:
            for m in tar.getmembers():
                if not m.isfile():
                    continue
                rel = m.name.split("/", 1)[1] if "/" in m.name else m.name
                target = dest / rel
                checked += 1
                if not target.exists() or target.stat().st_size != m.size:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    # esbuild 安装后会把 bin 和平台包里的二进制做成硬链接，先断开再写，免得改坏另一个
                    target.unlink(missing_ok=True)
                    target.write_bytes(tar.extractfile(m).read())
                    target.chmod(m.mode | 0o600)
                    fixed += 1
    print(f"核对 {checked} 个文件，重写 {fixed} 个；缓存里找不到的包 {missing} 个")
    return 0


if __name__ == "__main__":
    sys.exit(main())
